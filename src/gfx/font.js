function glyph(ch) {
  if (ch === '№') return null;
  return G[ch] || G[ch.toUpperCase()] || G['?'];
}

export function textWidth(str, gap = 1) {
  let w = 0;
  for (const ch of str) {
    if (ch === '№') w += 4 + gap + 2 + gap;
    else w += glyph(ch)[0].length + gap;
  }
  return Math.max(0, w - gap);
}

// put(x, y) — рисует один пиксель; возвращает ширину надписи
export function drawText(put, str, x, y, gap = 1) {
  let cx = x;
  const draw = (g) => {
    g.forEach((row, yy) => [...row].forEach((c, xx) => c === '#' && put(cx + xx, y + yy)));
    cx += g[0].length + gap;
  };
  for (const ch of str) {
    if (ch === '№') {
      draw(G.N);
      draw(G['°']);
    } else draw(glyph(ch));
  }
  return cx - x - gap;
}
