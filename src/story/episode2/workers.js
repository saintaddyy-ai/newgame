const OFF = ['fri', 'sat', 'sun'];

function build(list, place, apron) {
  return list.map(([name, trait, shift, quirk], i) => {
    const seed = hashStr(`${place}_${name}`);
    return {
      id: `${place}_w${i}`, name, trait, shift, quirk, place,
      off: i % 4 === 3 ? OFF[seed % 3] : null,
      spec: randomSpec(seed, { apron, female: /[ая]$/.test(name) && !['Гоша-младший', 'Тоха', 'Миша', 'Сеня', 'Ден', 'Тима', 'Петя', 'Саша', 'Глеб', 'Арсен', 'Костя', 'Гриша', 'Денис', 'Жора', 'Вадик', 'Марат', 'Рустам', 'Эд', 'Борис', 'Влад'].includes(name) }),
    };
  });
}

