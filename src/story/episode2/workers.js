export function workerHello(w, m) {
  const t = TRAITS[w.trait];
  return m >= 1 ? t.good : m <= -1 ? t.bad : t.ok;
}

// Настроение работника на сегодня (без отношения к Марку — он для них просто клиент)
export function workerMood(w) {
  const h = hashStr(`${w.id}|${day()}`) % 5;
  const base = { angry: -1, rude: -1, tired: -1, sweet: 1, chatty: 1 }[w.trait] || 0;
  return Math.max(-2, Math.min(2, base + (h === 0 ? -1 : h === 4 ? 1 : 0)));
}

export function prepareWorkers(scene, list) {
  list.forEach((w) => (w.sprite = personTexture(scene, w.spec, `w_${w.id}`)));
}
