// Смены: утро 8–14, день 12–18, вечер 17–23, ночь 22–4
const SHIFTS = { morning: [at(8), at(14)], day: [at(12), at(18)], evening: [at(17), at(23)], night: [at(22), at(28)] };

export function onShift(w) {
  const [a, b] = SHIFTS[w.shift];
  const t = now();
  // Выходной у каждого свой (по имени), чтобы составы менялись от дня к дню
  if (w.off === day()) return false;
  return t >= a && t < b;
}

